/** Çalışan dosyanın yolundan oyun adı çıkarır (Steam, Epic, Riot, Xbox, EA, Ubisoft, GOG klasörleri) */
export function gameFromPath(p: string | undefined | null): string | null {
  if (!p) return null;
  const s = p.replace(/\//g, '\\');
  const pats: RegExp[] = [
    /\\steamapps\\common\\([^\\]+)\\/i,
    /\\Epic Games\\([^\\]+)\\/i,
    /\\Riot Games\\([^\\]+)\\/i,
    /\\XboxGames\\([^\\]+)\\/i,
    /\\EA Games\\([^\\]+)\\/i,
    /\\Electronic Arts\\([^\\]+)\\/i,
    /\\Ubisoft Game Launcher\\games\\([^\\]+)\\/i,
    /\\GOG Galaxy\\Games\\([^\\]+)\\/i,
    /\\Battle\.net\\([^\\]+)\\/i,
  ];
  for (const re of pats) {
    const m = re.exec(s);
    if (!m) continue;
    const name = m[1].trim();
    if (!name || /^(launcher|riot client|common|redist|_commonredist|directx|steamworks shared)$/i.test(name)) return null;
    return name;
  }
  return null;
}
